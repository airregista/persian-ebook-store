export function getMockBookReviews(bookId: string): BookReview[] {
  // Deterministic seed from bookId
  let seed = 0;
  for (let i = 0; i < bookId.length; i++) {
    seed = (seed * 31 + bookId.charCodeAt(i)) & 0xffffffff;
  }
  const count = 3 + (Math.abs(seed) % 3); // 3 to 5 reviews
  const reviews: BookReview[] = [];

  for (let i = 0; i < count; i++) {
    const authorIdx = (Math.abs(seed) + i * 3) % REVIEW_AUTHORS.length;
    const author = REVIEW_AUTHORS[authorIdx];
    const isAudio = (seed + i) % 2 === 0;
    const pool = isAudio ? REVIEW_COMMENTS.audio : REVIEW_COMMENTS.default;
    const text = pool[(Math.abs(seed) + i) % pool.length];
    const rating = 4 + ((Math.abs(seed) + i) % 2); // 4 or 5
    const month = ((Math.abs(seed) + i * 2) % 11) + 1;
    const day = ((Math.abs(seed) + i * 5) % 28) + 1;
    const year = 1403;
    const date = `${year}/${month < 10 ? '0' + month : month}/${day < 10 ? '0' + day : day}`;
    const likes = 8 + ((Math.abs(seed) + i * 7) % 65);

    reviews.push({
      id: `rev-${bookId}-${i + 1}`,
      user: author,
      rating,
      date,
      text,
      likes
    });
  }

  return reviews;
}
